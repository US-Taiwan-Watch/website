/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require('fs')
const path = require('path')
const csvtojson = require('csvtojson')
const fetch = require('node-fetch')

/**
 * @typedef {Object} CsvRecord
 * @property {string} description - Description of the translation entry
 * @property {string} namespace - Namespace for grouping translations
 * @property {string} key - Unique identifier for the translation
 * @property {string} [key: string] - Translation value for each language
 */

const OUTPUT_FOLDER = 'src/common/lib/i18n/locales/'

/** @type {(keyof CsvRecord)[]} */
const nonLanguageKeys = ['description', 'namespace', 'key']

/**
 * 從遠端抓取語言包的 CSV 檔
 * @returns {Promise<string>} The CSV content as a string
 * @throws {Error} If Axios request fails
 */

const fetchCsv = async () => {
  const url =
    'https://docs.google.com/spreadsheets/d/e/2PACX-1vSTzF1H6GpzEbJX7orNFPIsrTqHAAx-qTPmUr0cHYZQ2r6eG2FCKatbX2I2oMXEQa2Zw8NpquxE-3Fi/pub?gid=0&single=true&output=csv'
  return (await fetch(url)).text()
}

/**
 * 從遠端抓取 SEO 語言包的 CSV 檔
 * @returns {Promise<string>} The CSV content as a string
 * @throws {Error} If Axios request fails
 */

const fetchSeoCsv = async () => {
  const url =
    'https://docs.google.com/spreadsheets/d/e/2PACX-1vSTzF1H6GpzEbJX7orNFPIsrTqHAAx-qTPmUr0cHYZQ2r6eG2FCKatbX2I2oMXEQa2Zw8NpquxE-3Fi/pub?gid=1386324097&single=true&output=csv'
  return (await fetch(url)).text()
}

/**
 * Extracts unique languages and namespaces from CSV records
 * @param {CsvRecord[]} records - Array of CSV records
 * @returns {{ languages: Set<string>, namespaces: Set<string> }} Object containing arrays of languages and namespaces
 */
const getLanguageAndNamespaceSet = (records) => {
  const languages = new Set()
  const namespaces = new Set()
  for (const record of records) {
    Object.keys(record).forEach((key) => {
      if (nonLanguageKeys.includes(key)) return
      languages.add(key)
    })
    namespaces.add(record.namespace)
  }
  return { languages, namespaces }
}

const run = async () => {
  /**
   * @returns {Promise<CsvRecord[]>}
   */
  const generateI18n = () => {
    // eslint-disable-next-line no-async-promise-executor
    return new Promise(async (resolve) => {
      // 處理語言包
      const csvString = await fetchCsv()

      /** @type {CsvRecord[]} */
      let records = await csvtojson({ trim: false }).fromString(csvString)

      records = records
        // 過濾掉 `key` 為空的項目
        .filter(({ key }) => key)

      resolve(records)
    })
  }

  /**
   * @returns {Promise<CsvRecord[]>}
   */
  const generateSeoI18n = () => {
    // eslint-disable-next-line no-async-promise-executor
    return new Promise(async (resolve) => {
      // 處理 SEO 語言包
      const seoCsvString = await fetchSeoCsv()

      /** @type {CsvRecord[]} */
      let seoRecords = await csvtojson({ trim: false }).fromString(seoCsvString)

      seoRecords = seoRecords
        // 過濾掉 `key` 為空的項目以及 `namespace` 非 `seo_` 開頭的項目
        .filter(({ key, namespace }) => key && namespace.startsWith('seo_'))

      resolve(seoRecords)
    })
  }

  // 合併語言包與 SEO 語言包
  const [records, seoRecords] = await Promise.all([
    generateI18n(),
    generateSeoI18n(),
  ])
  const mergedRecords = [...records, ...seoRecords]

  const { languages, namespaces } = getLanguageAndNamespaceSet(mergedRecords)

  // <language, <namespace, <key, value>>>
  /** @type {Record<string, Record<string, Record<string, string>>>} */
  const i18nContentMap = {}
  for (const lang of languages) {
    i18nContentMap[lang] = {}
    for (const namespace of namespaces) {
      i18nContentMap[lang][namespace] = {
        '//': [
          '---------------------------------------------------',
          ' ⚠️ Do not edit this file. It is machine generated. ',
          '---------------------------------------------------',
        ],
      }
    }
  }

  // Populate the i18nContentMap
  mergedRecords.forEach((record) => {
    languages.forEach((lang) => {
      // 排除空字串或只包含空格的字串
      if (!record[lang]?.trim()) return
      i18nContentMap[lang][record.namespace][record.key] = record[lang]
    })
  })

  // Create directories and write files
  for (const lang of languages) {
    // Create language directory
    const langDir = path.join(OUTPUT_FOLDER, lang)
    fs.mkdirSync(langDir, { recursive: true })

    // Write each namespace file
    for (const namespace of namespaces) {
      const filePath = path.join(langDir, `${namespace}.json`)
      fs.writeFileSync(
        filePath,
        JSON.stringify(i18nContentMap[lang]?.[namespace], null, 2),
        { encoding: 'utf-8' }
      )
      console.log(`Created: ${filePath}`)
    }
    console.log('\x1b[32m', '✅ 已建立語言包 ', lang, '\x1b[0m')
  }
}

run()
